// dist/kit/<module>.css: the modules of the homemade-claude-kit design contract (CONTRACT_VERSION),
// one file per module. The roles come from the kit tier (tokens/kit/, group kit.<module>), whose
// tokens alias semantic tokens. Values are literal, as in kit-contract.css: the kit resolver checks
// the contract's text pairs on hex values and inlines only url() values. The class modules
// (document, slide-frame, dark, print) add the class rules of css/kit/<module>.css, written by hand
// against contract roles only (Plan-0002 increment 02, build/kit-classes.md). The dark module
// (Plan-0003 increment 04) is written by the dark theme run (style-dictionary.config.mjs darkTheme),
// where the same semantic aliases resolve to their dark values; its classes are drawn by the kit's
// own dark layer, so css/kit/dark.css holds no rule.
import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { LICENCE_BANNER } from "../licence-banner.mjs";
import { embeddedFontFaces } from "./kit-contract.mjs";

// The kit contract version this build targets: kit-manifest.json declares it and every module
// header names it; the tests compare it with the vendored modules.json.
export const CONTRACT_VERSION = "2.1.0";

export const KIT_TOKEN_MODULES = ["core", "dataviz", "type", "space-shape", "brand"];
export const KIT_CLASS_MODULES = ["document", "slide-frame", "dark", "print"];
// Every module this package provides, in the contract's order.
export const KIT_MODULES = ["core", "dataviz", "type", "space-shape", "document", "slide-frame", "dark", "print", "brand"];
// The modules whose values are the dark theme's, built by the dark run; every other one by the light run.
export const KIT_DARK_MODULES = ["dark"];
export const KIT_LIGHT_MODULES = KIT_MODULES.filter((module) => !KIT_DARK_MODULES.includes(module));

const ROOT = fileURLToPath(new URL("../..", import.meta.url));

const inModule = (module) => (token) => token.path[0] === "kit" && token.path[1] === module;

// The hand-written rules of a class module, without the banner the module file already opens with.
const classRules = (module) => {
  const source = readFileSync(`${ROOT}css/kit/${module}.css`, "utf8");
  if (!source.startsWith(LICENCE_BANNER)) throw new Error(`css/kit/${module}.css must start with the copyright banner`);
  return source.slice(LICENCE_BANNER.length).replace(/^\n+/, "").replace(/\n*$/, "\n");
};

const header = (module) =>
  KIT_DARK_MODULES.includes(module)
    ? [
        ` * MedQuantis ${module} module of the homemade-claude-kit design contract ${CONTRACT_VERSION}. The roles are`,
        " * generated from tokens/kit/ by the design-system build, resolved in the dark theme (ADR-0007),",
        " * on :root only; the kit's own dark layer remaps the light roles to them on a dark slide or page",
        " * and draws the dark, dark-key and dark-accent classes. Do not edit this file. kit-manifest.json",
        " * lists it. For kit renderers only: the unprefixed names collide with app and Tailwind variables.",
      ]
    : KIT_CLASS_MODULES.includes(module)
    ? [
        ` * MedQuantis ${module} module of the homemade-claude-kit design contract ${CONTRACT_VERSION}. The roles are`,
        " * generated from tokens/kit/ by the design-system build; the class rules after them are copied",
        ` * from css/kit/${module}.css, written by hand against contract roles. Do not edit this file.`,
        " * kit-manifest.json lists it. For kit renderers only: the unprefixed names collide with app and",
        " * Tailwind variables.",
      ]
    : [
        ` * MedQuantis values for the ${module} module of the homemade-claude-kit design contract ${CONTRACT_VERSION},`,
        " * generated from tokens/kit/ by the design-system build. Do not edit. kit-manifest.json lists it.",
        " * For kit renderers only: the unprefixed names collide with app and Tailwind variables.",
      ];

// Under the kit contract the fonts are the @font-face rules of any provided module; core carries
// the same embedded latin faces as kit-contract.css, as data because the kit inlines the module.
export const kitModuleFormat = (module) => ({ dictionary }) => {
  const lines = dictionary.allTokens.filter(inModule(module)).map((token) => `  --${token.path.at(-1)}: ${token.$value};`);
  if (lines.length === 0) throw new Error(`dist/kit/${module}.css: the kit tier has no kit.${module} group`);
  const faces = module === "core" ? embeddedFontFaces().flatMap((rule) => [rule, ""]) : [];
  const rules = KIT_CLASS_MODULES.includes(module) ? [classRules(module)].filter((text) => text.trim()) : [];
  return [
    LICENCE_BANNER,
    "/*",
    ...header(module),
    " */",
    ":root {",
    ...lines,
    "}",
    "",
    ...faces,
    ...rules,
  ].join("\n");
};
