#!/usr/bin/env node
// Copies the variable woff2 files and OFL licences of the three brand families from their
// exact-pinned fontsource packages into fonts/<family>/ and writes fonts/fonts.css.
// One variable file per subset and style covers every weight, so apps asking for 700 get the
// real bold instead of a synthesised one. latin carries French, German and Italian (U+00C0
// to U+00FF, oe ligature, euro sign, typographic quotes); latin-ext is fetched by the browser
// only when a page uses a character in its range (names such as Dvořák).
import { copyFileSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { LICENCE_BANNER } from "../build/licence-banner.mjs";

const SUBSETS = ["latin-ext", "latin"];

const family = (dir, name, styles) => ({
  dir,
  family: name,
  package: `@fontsource-variable/${dir}`,
  styles,
  files: styles.flatMap((style) => SUBSETS.map((subset) => ({ subset, style, file: `${dir}-${subset}-wght-${style}.woff2` }))),
});

// Newsreader is the body serif, so it ships its italic; Outfit has none, Geist Mono needs none.
export const FONTS = [family("outfit", "Outfit", ["normal"]), family("newsreader", "Newsreader", ["normal", "italic"]), family("geist-mono", "Geist Mono", ["normal"])];

const quote = (name) => (/\s/.test(name) ? `'${name}'` : name);

export function fontsCss(root) {
  const blocks = FONTS.flatMap((font) => {
    const pkg = join(root, "node_modules", font.package);
    const { variable } = JSON.parse(readFileSync(join(pkg, "metadata.json"), "utf8"));
    const ranges = JSON.parse(readFileSync(join(pkg, "unicode.json"), "utf8"));
    return font.files.map(({ subset, style, file }) =>
      [
        "@font-face {",
        `  font-family: ${quote(font.family)};`,
        `  font-style: ${style};`,
        `  font-weight: ${variable.wght.min} ${variable.wght.max};`,
        "  font-display: swap;",
        `  src: url(./${font.dir}/${file}) format('woff2');`,
        `  unicode-range: ${ranges[subset]};`,
        "}",
      ].join("\n"),
    );
  });
  const versions = FONTS.map((font) => `${font.package} ${JSON.parse(readFileSync(join(root, "node_modules", font.package, "package.json"), "utf8")).version}`);
  return [
    LICENCE_BANNER,
    "/*",
    " * MedQuantis brand fonts, self-hosted (SIL Open Font License, see each folder's OFL.txt).",
    ` * Generated by scripts/copy-fonts.mjs from ${versions.join(", ")}. Do not edit.`,
    " * Paths are relative to this file; deploy the folder as a whole.",
    " */",
    blocks.join("\n\n"),
    "",
  ].join("\n");
}

export function copyFonts(root) {
  const out = join(root, "fonts");
  rmSync(out, { recursive: true, force: true });
  for (const font of FONTS) {
    const pkg = join(root, "node_modules", font.package);
    mkdirSync(join(out, font.dir), { recursive: true });
    for (const { file } of font.files) copyFileSync(join(pkg, "files", file), join(out, font.dir, file));
    copyFileSync(join(pkg, "LICENSE"), join(out, font.dir, "OFL.txt"));
  }
  writeFileSync(join(out, "fonts.css"), fontsCss(root));
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) copyFonts(process.cwd());
